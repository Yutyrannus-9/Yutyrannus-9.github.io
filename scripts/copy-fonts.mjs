// Copies the IBM Plex faces the site uses (latin + latin-ext subsets) from
// @fontsource into public/fonts and writes public/fonts/fonts.css.
// The stylesheet is loaded without blocking first paint (see Base.astro), so
// text appears in the system font first and IBM Plex swaps in.
//
//   node scripts/copy-fonts.mjs

import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { ROOT } from './lib/surfaces.mjs';

const FACES = [
  ['ibm-plex-sans', 'IBM Plex Sans', 400],
  ['ibm-plex-sans', 'IBM Plex Sans', 500],
  ['ibm-plex-sans-condensed', 'IBM Plex Sans Condensed', 500],
  ['ibm-plex-mono', 'IBM Plex Mono', 400],
];
const SUBSETS = ['latin', 'latin-ext'];
const out = path.join(ROOT, 'public/fonts');
mkdirSync(out, { recursive: true });

let css = '/* Generated by scripts/copy-fonts.mjs from @fontsource (SIL Open Font License 1.1). */\n';
for (const [pkg, family, weight] of FACES) {
  const dir = path.join(ROOT, 'node_modules/@fontsource', pkg);
  const src = readFileSync(path.join(dir, `${weight}.css`), 'utf8');
  for (const subset of SUBSETS) {
    const file = `${pkg}-${subset}-${weight}-normal.woff2`;
    const block = src.split('@font-face').find((b) => b.includes(`${pkg}-${subset}-${weight}-normal.woff2`));
    const range = /unicode-range:\s*([^;]+);/.exec(block ?? '')?.[1];
    if (!range) throw new Error(`no unicode-range for ${file}`);
    copyFileSync(path.join(dir, 'files', file), path.join(out, file));
    css += `@font-face{font-family:'${family}';font-style:normal;font-weight:${weight};font-display:swap;src:url(/fonts/${file}) format('woff2');unicode-range:${range}}\n`;
  }
}
writeFileSync(path.join(out, 'fonts.css'), css);
console.log('fonts.css written with', FACES.length * SUBSETS.length, 'faces');
